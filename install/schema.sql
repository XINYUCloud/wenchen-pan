-- 文谶云盘 数据表结构 (MySQL 5.6+ / MariaDB 10+, utf8mb4)
-- 表前缀固定 wc_

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_user` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `email` VARCHAR(100) NOT NULL DEFAULT '',
  `pass` VARCHAR(255) NOT NULL DEFAULT '',
  `nick` VARCHAR(50) NOT NULL DEFAULT '',
  `avatar` VARCHAR(255) NOT NULL DEFAULT '',
  `sig` VARCHAR(200) NOT NULL DEFAULT '',
  `quota` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `used` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `verified` TINYINT NOT NULL DEFAULT 0,
  `status` TINYINT NOT NULL DEFAULT 0 COMMENT '0待验证 1正常 2封禁',
  `role` VARCHAR(10) NOT NULL DEFAULT 'user' COMMENT 'user/admin/super',
  `ban_reason` VARCHAR(200) NOT NULL DEFAULT '',
  `reg_ip` VARCHAR(45) NOT NULL DEFAULT '',
  `reg_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `last_ip` VARCHAR(45) NOT NULL DEFAULT '',
  `last_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `login_cnt` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `email` (`email`),
  KEY `status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_folder` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `uid` INT UNSIGNED NOT NULL DEFAULT 0,
  `name` VARCHAR(120) NOT NULL DEFAULT '',
  `parent` INT UNSIGNED NOT NULL DEFAULT 0,
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `uid` (`uid`,`parent`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_file` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `uid` INT UNSIGNED NOT NULL DEFAULT 0,
  `folder` INT UNSIGNED NOT NULL DEFAULT 0,
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `ext` VARCHAR(12) NOT NULL DEFAULT '',
  `kind` VARCHAR(12) NOT NULL DEFAULT 'other',
  `size` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `sha1` CHAR(40) NOT NULL DEFAULT '',
  `path` VARCHAR(255) NOT NULL DEFAULT '',
  `thumb` VARCHAR(255) NOT NULL DEFAULT '',
  `tags` VARCHAR(255) NOT NULL DEFAULT '',
  `note` VARCHAR(255) NOT NULL DEFAULT '',
  `star` TINYINT NOT NULL DEFAULT 0,
  `view` INT UNSIGNED NOT NULL DEFAULT 0,
  `down` INT UNSIGNED NOT NULL DEFAULT 0,
  `traffic` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `del_time` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0=未删除，非0=进回收站时间',
  PRIMARY KEY (`id`),
  KEY `uid` (`uid`,`folder`,`del_time`),
  KEY `sha1` (`sha1`),
  KEY `kind` (`kind`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_share` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `code` CHAR(12) NOT NULL DEFAULT '',
  `uid` INT UNSIGNED NOT NULL DEFAULT 0,
  `file_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `folder_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `title` VARCHAR(255) NOT NULL DEFAULT '',
  `pwd` VARCHAR(255) NOT NULL DEFAULT '',
  `expire` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0=永久',
  `max_down` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0=不限',
  `down` INT UNSIGNED NOT NULL DEFAULT 0,
  `view` INT UNSIGNED NOT NULL DEFAULT 0,
  `direct` TINYINT NOT NULL DEFAULT 0 COMMENT '1=允许直链流',
  `pub` TINYINT NOT NULL DEFAULT 0 COMMENT '1=允许进入首页/排行公开展示',
  `status` TINYINT NOT NULL DEFAULT 1 COMMENT '1有效 0已关闭',
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  KEY `uid` (`uid`),
  KEY `file_id` (`file_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_share_log` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `code` VARCHAR(12) NOT NULL DEFAULT '',
  `ip` VARCHAR(45) NOT NULL DEFAULT '',
  `ua` VARCHAR(255) NOT NULL DEFAULT '',
  `result` VARCHAR(30) NOT NULL DEFAULT '',
  `bytes` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `code` (`code`,`add_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_announce` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `title` VARCHAR(200) NOT NULL DEFAULT '',
  `content` TEXT,
  `author` VARCHAR(50) NOT NULL DEFAULT '',
  `top` TINYINT NOT NULL DEFAULT 0,
  `status` TINYINT NOT NULL DEFAULT 1 COMMENT '1发布 0草稿',
  `view` INT UNSIGNED NOT NULL DEFAULT 0,
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `edit_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `status` (`status`,`top`,`add_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_notice` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `uid` INT UNSIGNED NOT NULL DEFAULT 0,
  `title` VARCHAR(200) NOT NULL DEFAULT '',
  `content` TEXT,
  `type` VARCHAR(20) NOT NULL DEFAULT 'system',
  `is_read` TINYINT NOT NULL DEFAULT 0,
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `uid` (`uid`,`is_read`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_setting` (
  `k` VARCHAR(64) NOT NULL,
  `v` TEXT,
  PRIMARY KEY (`k`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_mail_tpl` (
  `k` VARCHAR(32) NOT NULL,
  `name` VARCHAR(64) NOT NULL DEFAULT '',
  `subject` VARCHAR(200) NOT NULL DEFAULT '',
  `body` TEXT,
  PRIMARY KEY (`k`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_report` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `code` VARCHAR(12) NOT NULL DEFAULT '',
  `url` VARCHAR(255) NOT NULL DEFAULT '',
  `reason` VARCHAR(50) NOT NULL DEFAULT '',
  `detail` TEXT,
  `contact` VARCHAR(100) NOT NULL DEFAULT '',
  `ip` VARCHAR(45) NOT NULL DEFAULT '',
  `status` TINYINT NOT NULL DEFAULT 0 COMMENT '0待处理 1已处理 2驳回',
  `handle` VARCHAR(255) NOT NULL DEFAULT '',
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  `edit_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_log` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `type` VARCHAR(20) NOT NULL DEFAULT 'system',
  `uid` INT UNSIGNED NOT NULL DEFAULT 0,
  `uname` VARCHAR(100) NOT NULL DEFAULT '',
  `action` VARCHAR(100) NOT NULL DEFAULT '',
  `detail` TEXT,
  `ip` VARCHAR(45) NOT NULL DEFAULT '',
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `type` (`type`,`add_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_kv` (
  `k` VARCHAR(191) NOT NULL,
  `v` MEDIUMTEXT,
  `expire_at` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`k`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_chunk` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `upload_id` CHAR(40) NOT NULL DEFAULT '',
  `uid` INT UNSIGNED NOT NULL DEFAULT 0,
  `sha1` CHAR(40) NOT NULL DEFAULT '',
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `size` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `total` INT UNSIGNED NOT NULL DEFAULT 0,
  `folder` INT UNSIGNED NOT NULL DEFAULT 0,
  `status` TINYINT NOT NULL DEFAULT 0 COMMENT '0上传中 1已完成 2已放弃',
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `upload_id` (`upload_id`),
  KEY `uid` (`uid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_chunk_part` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `upload_id` CHAR(40) NOT NULL DEFAULT '',
  `i` INT UNSIGNED NOT NULL DEFAULT 0,
  `path` VARCHAR(255) NOT NULL DEFAULT '',
  `size` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `add_time` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `up_i` (`upload_id`,`i`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `wc_stat` (
  `d` DATE NOT NULL,
  `upload_cnt` INT UNSIGNED NOT NULL DEFAULT 0,
  `upload_bytes` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `down_cnt` INT UNSIGNED NOT NULL DEFAULT 0,
  `down_bytes` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `new_user` INT UNSIGNED NOT NULL DEFAULT 0,
  `share_cnt` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`d`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
